-- Migration v2.26.0: OPD credit company claim tables
-- Issue: #25847 (OPD credit company claims, part 1)
--
-- Creates CREDITCOMPANYCLAIM and CREDITCOMPANYCLAIMITEM, mapped by the CreditCompanyClaim and
-- CreditCompanyClaimItem entities. Production has no DDL generation, so run this before
-- deploying a build that includes those entities.
--
-- Safe to re-run: each table is created only when missing.
--
-- UNIVERSAL: detects actual table-name case via INFORMATION_SCHEMA so this works on both
-- case-sensitive (Linux, lower_case_table_names=0) and case-insensitive (Windows/Azure) MySQL.
-- New tables are created in the same case as the existing WEBUSER table.

SELECT 'Migration v2.26.0 - OPD credit company claim tables' AS status;

SET @webuser_table = (
    SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES
    WHERE TABLE_SCHEMA = DATABASE() AND UPPER(TABLE_NAME) = 'WEBUSER' LIMIT 1
);
SET @institution_table = (
    SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES
    WHERE TABLE_SCHEMA = DATABASE() AND UPPER(TABLE_NAME) = 'INSTITUTION' LIMIT 1
);
SET @department_table = (
    SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES
    WHERE TABLE_SCHEMA = DATABASE() AND UPPER(TABLE_NAME) = 'DEPARTMENT' LIMIT 1
);
SET @bill_table = (
    SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES
    WHERE TABLE_SCHEMA = DATABASE() AND UPPER(TABLE_NAME) = 'BILL' LIMIT 1
);

SELECT CONCAT('WEBUSER: ', COALESCE(@webuser_table, 'NOT FOUND'),
              ', INSTITUTION: ', COALESCE(@institution_table, 'NOT FOUND'),
              ', DEPARTMENT: ', COALESCE(@department_table, 'NOT FOUND'),
              ', BILL: ', COALESCE(@bill_table, 'NOT FOUND')) AS info;

-- Case for the new tables follows the existing WEBUSER table
SET @claim_table = IF(@webuser_table = UPPER(@webuser_table), 'CREDITCOMPANYCLAIM', 'creditcompanyclaim');
SET @item_table = IF(@webuser_table = UPPER(@webuser_table), 'CREDITCOMPANYCLAIMITEM', 'creditcompanyclaimitem');

-- STEP 1: CREDITCOMPANYCLAIM
SET @exists = (
    SELECT COUNT(*) FROM INFORMATION_SCHEMA.TABLES
    WHERE TABLE_SCHEMA = DATABASE() AND UPPER(TABLE_NAME) = 'CREDITCOMPANYCLAIM'
);
SET @sql = IF(@webuser_table IS NULL OR @institution_table IS NULL OR @department_table IS NULL,
    'SELECT "SKIPPED: WEBUSER, INSTITUTION or DEPARTMENT table not found" AS status',
    IF(@exists > 0,
        'SELECT "SKIPPED: CREDITCOMPANYCLAIM already exists" AS status',
        CONCAT('CREATE TABLE ', @claim_table, ' (
            ID BIGINT NOT NULL AUTO_INCREMENT,
            CANCELLEDAT DATETIME DEFAULT NULL,
            CLAIMNO VARCHAR(255) DEFAULT NULL,
            CLAIMEDTOTAL DOUBLE DEFAULT NULL,
            COMPANYREFERENCE VARCHAR(255) DEFAULT NULL,
            CREATEDAT DATETIME DEFAULT NULL,
            REJECTREASON VARCHAR(255) DEFAULT NULL,
            REJECTEDAT DATETIME DEFAULT NULL,
            RESUBMITCOUNT INT DEFAULT NULL,
            RETIRED TINYINT(1) DEFAULT 0,
            RETIREDAT DATETIME DEFAULT NULL,
            STATUS VARCHAR(255) DEFAULT NULL,
            SUBMITTEDAT DATETIME DEFAULT NULL,
            CANCELLEDBY_ID BIGINT DEFAULT NULL,
            CREATER_ID BIGINT DEFAULT NULL,
            CREDITCOMPANY_ID BIGINT DEFAULT NULL,
            DEPARTMENT_ID BIGINT DEFAULT NULL,
            INSTITUTION_ID BIGINT DEFAULT NULL,
            REJECTER_ID BIGINT DEFAULT NULL,
            RETIRER_ID BIGINT DEFAULT NULL,
            SUBMITTER_ID BIGINT DEFAULT NULL,
            PRIMARY KEY (ID),
            KEY FK_CREDITCOMPANYCLAIM_CREDITCOMPANY_ID (CREDITCOMPANY_ID),
            KEY FK_CREDITCOMPANYCLAIM_SUBMITTER_ID (SUBMITTER_ID),
            KEY FK_CREDITCOMPANYCLAIM_RETIRER_ID (RETIRER_ID),
            KEY FK_CREDITCOMPANYCLAIM_CREATER_ID (CREATER_ID),
            KEY FK_CREDITCOMPANYCLAIM_CANCELLEDBY_ID (CANCELLEDBY_ID),
            KEY FK_CREDITCOMPANYCLAIM_DEPARTMENT_ID (DEPARTMENT_ID),
            KEY FK_CREDITCOMPANYCLAIM_INSTITUTION_ID (INSTITUTION_ID),
            KEY FK_CREDITCOMPANYCLAIM_REJECTER_ID (REJECTER_ID),
            CONSTRAINT FK_CREDITCOMPANYCLAIM_CANCELLEDBY_ID FOREIGN KEY (CANCELLEDBY_ID) REFERENCES ', @webuser_table, ' (ID),
            CONSTRAINT FK_CREDITCOMPANYCLAIM_CREATER_ID FOREIGN KEY (CREATER_ID) REFERENCES ', @webuser_table, ' (ID),
            CONSTRAINT FK_CREDITCOMPANYCLAIM_CREDITCOMPANY_ID FOREIGN KEY (CREDITCOMPANY_ID) REFERENCES ', @institution_table, ' (ID),
            CONSTRAINT FK_CREDITCOMPANYCLAIM_DEPARTMENT_ID FOREIGN KEY (DEPARTMENT_ID) REFERENCES ', @department_table, ' (ID),
            CONSTRAINT FK_CREDITCOMPANYCLAIM_INSTITUTION_ID FOREIGN KEY (INSTITUTION_ID) REFERENCES ', @institution_table, ' (ID),
            CONSTRAINT FK_CREDITCOMPANYCLAIM_REJECTER_ID FOREIGN KEY (REJECTER_ID) REFERENCES ', @webuser_table, ' (ID),
            CONSTRAINT FK_CREDITCOMPANYCLAIM_RETIRER_ID FOREIGN KEY (RETIRER_ID) REFERENCES ', @webuser_table, ' (ID),
            CONSTRAINT FK_CREDITCOMPANYCLAIM_SUBMITTER_ID FOREIGN KEY (SUBMITTER_ID) REFERENCES ', @webuser_table, ' (ID)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4')
    )
);
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- STEP 2: CREDITCOMPANYCLAIMITEM (references the claim table created above)
SET @claim_actual = (
    SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES
    WHERE TABLE_SCHEMA = DATABASE() AND UPPER(TABLE_NAME) = 'CREDITCOMPANYCLAIM' LIMIT 1
);
SET @exists = (
    SELECT COUNT(*) FROM INFORMATION_SCHEMA.TABLES
    WHERE TABLE_SCHEMA = DATABASE() AND UPPER(TABLE_NAME) = 'CREDITCOMPANYCLAIMITEM'
);
SET @sql = IF(@webuser_table IS NULL OR @bill_table IS NULL OR @claim_actual IS NULL,
    'SELECT "SKIPPED: WEBUSER, BILL or CREDITCOMPANYCLAIM table not found" AS status',
    IF(@exists > 0,
        'SELECT "SKIPPED: CREDITCOMPANYCLAIMITEM already exists" AS status',
        CONCAT('CREATE TABLE ', @item_table, ' (
            ID BIGINT NOT NULL AUTO_INCREMENT,
            CLAIMEDAMOUNT DOUBLE DEFAULT NULL,
            CREATEDAT DATETIME DEFAULT NULL,
            RETIRED TINYINT(1) DEFAULT 0,
            RETIREDAT DATETIME DEFAULT NULL,
            BILL_ID BIGINT DEFAULT NULL,
            CLAIM_ID BIGINT DEFAULT NULL,
            CREATER_ID BIGINT DEFAULT NULL,
            RETIRER_ID BIGINT DEFAULT NULL,
            PRIMARY KEY (ID),
            KEY FK_CREDITCOMPANYCLAIMITEM_CLAIM_ID (CLAIM_ID),
            KEY FK_CREDITCOMPANYCLAIMITEM_CREATER_ID (CREATER_ID),
            KEY FK_CREDITCOMPANYCLAIMITEM_RETIRER_ID (RETIRER_ID),
            KEY FK_CREDITCOMPANYCLAIMITEM_BILL_ID (BILL_ID),
            CONSTRAINT FK_CREDITCOMPANYCLAIMITEM_BILL_ID FOREIGN KEY (BILL_ID) REFERENCES ', @bill_table, ' (ID),
            CONSTRAINT FK_CREDITCOMPANYCLAIMITEM_CLAIM_ID FOREIGN KEY (CLAIM_ID) REFERENCES ', @claim_actual, ' (ID),
            CONSTRAINT FK_CREDITCOMPANYCLAIMITEM_CREATER_ID FOREIGN KEY (CREATER_ID) REFERENCES ', @webuser_table, ' (ID),
            CONSTRAINT FK_CREDITCOMPANYCLAIMITEM_RETIRER_ID FOREIGN KEY (RETIRER_ID) REFERENCES ', @webuser_table, ' (ID)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4')
    )
);
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
